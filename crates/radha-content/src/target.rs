//! What a content bundle fills: one of the nine products or one of the two
//! exam passage pools, and the review status of every passage in it.
//!
//! Exam pools are not products (they have no Home card); they hold the
//! passages exam profiles draw from (P09 links profiles to pools).

use radha_core::{CoreError, Result};
use radha_layouts::LayoutId;
use serde::{Deserialize, Serialize};

use crate::ProductId;

/// Review status of a passage. Shown honestly in the UI; never upgraded by
/// the importer.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default, Serialize, Deserialize)]
pub enum ContentStatus {
    /// The source records a completed review (`review.status = approved`).
    #[serde(rename = "verified")]
    Verified,
    /// Imported as-is from a source without a completed review (AI-drafted
    /// or deterministic generation by the source project).
    #[default]
    #[serde(rename = "provisional")]
    Provisional,
    /// Generated by Radha's own pipeline; awaiting human review and never
    /// presented as verified.
    #[serde(rename = "generated-review-pending")]
    GeneratedReviewPending,
}

impl ContentStatus {
    /// The SQLite / report value.
    #[must_use]
    pub fn as_str(self) -> &'static str {
        match self {
            ContentStatus::Verified => "verified",
            ContentStatus::Provisional => "provisional",
            ContentStatus::GeneratedReviewPending => "generated-review-pending",
        }
    }

    /// Parse [`ContentStatus::as_str`].
    ///
    /// # Errors
    ///
    /// [`CoreError::Malformed`] for an unknown value.
    pub fn parse(raw: &str) -> Result<Self> {
        match raw {
            "verified" => Ok(ContentStatus::Verified),
            "provisional" => Ok(ContentStatus::Provisional),
            "generated-review-pending" => Ok(ContentStatus::GeneratedReviewPending),
            other => Err(CoreError::malformed(
                "content status",
                other,
                "unknown status",
            )),
        }
    }
}

/// List-card metadata of one exercise: everything a grid shows, never the
/// text (P04 "list queries metadata only").
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExerciseMeta {
    /// Database id (pass to `load`).
    pub id: i64,
    /// 1-based position.
    pub number: u32,
    /// Title.
    pub title: String,
    /// Curriculum grouping.
    pub category: Option<String>,
    /// 1–5.
    pub difficulty: Option<u8>,
    /// Review status.
    pub status: ContentStatus,
    /// Hindi Learn track.
    pub track: Option<String>,
    /// Words in the text (`None` for rows imported before P04).
    pub word_count: Option<u32>,
}

/// List-card metadata of one exam passage.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExamPassageMeta {
    /// Database id.
    pub id: i64,
    /// 1-based position in the pool.
    pub number: u32,
    /// Title.
    pub title: String,
    /// Grouping from the source.
    pub category: Option<String>,
    /// 1–5.
    pub difficulty: Option<u8>,
    /// Words in the (trimmed) passage.
    pub word_count: u32,
    /// Review status.
    pub status: ContentStatus,
}

/// An exam passage pool, per language.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ExamPool {
    /// Unicode Hindi, typed on GAIL or CBI; a Kruti Dev legacy form is
    /// generated at import.
    Hindi,
    /// English, typed on QWERTY.
    English,
}

impl ExamPool {
    /// Stable identifier (`exam_pools.slug`, bundle `product` field).
    #[must_use]
    pub fn slug(self) -> &'static str {
        match self {
            ExamPool::Hindi => "exam-pool-hindi",
            ExamPool::English => "exam-pool-english",
        }
    }

    /// `exam_pools.language`.
    #[must_use]
    pub fn language(self) -> &'static str {
        match self {
            ExamPool::Hindi => "hindi",
            ExamPool::English => "english",
        }
    }

    /// Both pools.
    #[must_use]
    pub fn all() -> [ExamPool; 2] {
        [ExamPool::Hindi, ExamPool::English]
    }
}

/// Upper bound on an exam passage, in words (PRD 17.11: "≤ ~600 words").
pub const EXAM_MAX_WORDS: usize = 600;

/// A bundle's destination.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ContentTarget {
    /// One of the nine Home products.
    Product(ProductId),
    /// An exam passage pool.
    Pool(ExamPool),
}

impl ContentTarget {
    /// Every target: the nine products in Home order, then the two pools.
    #[must_use]
    pub fn all() -> Vec<ContentTarget> {
        let mut all: Vec<ContentTarget> = ProductId::all()
            .into_iter()
            .map(ContentTarget::Product)
            .collect();
        all.extend(ExamPool::all().map(ContentTarget::Pool));
        all
    }

    /// Stable identifier.
    #[must_use]
    pub fn slug(self) -> &'static str {
        match self {
            ContentTarget::Product(p) => p.slug(),
            ContentTarget::Pool(p) => p.slug(),
        }
    }

    /// Parse [`ContentTarget::slug`].
    ///
    /// # Errors
    ///
    /// [`CoreError::ResourceMissing`] for an unknown slug.
    pub fn from_slug(slug: &str) -> Result<Self> {
        ContentTarget::all()
            .into_iter()
            .find(|t| t.slug() == slug)
            .ok_or_else(|| CoreError::ResourceMissing {
                path: std::path::PathBuf::from(format!("content:{slug}")),
            })
    }

    /// The layout the stored `content` is typed on. The Hindi pool stores
    /// Unicode (typed on GAIL and CBI); its Kruti Dev form is separate.
    #[must_use]
    pub fn layout(self) -> LayoutId {
        match self {
            ContentTarget::Product(p) => p.layout(),
            ContentTarget::Pool(ExamPool::Hindi) => LayoutId::RemingtonGail,
            ContentTarget::Pool(ExamPool::English) => LayoutId::Qwerty,
        }
    }

    /// Every layout the stored `content` must be typeable on.
    #[must_use]
    pub fn typing_layouts(self) -> Vec<LayoutId> {
        match self {
            ContentTarget::Pool(ExamPool::Hindi) => {
                vec![LayoutId::RemingtonGail, LayoutId::RemingtonCbi]
            }
            other => vec![other.layout()],
        }
    }

    /// Whether every passage also carries a Kruti Dev legacy form.
    #[must_use]
    pub fn has_legacy_form(self) -> bool {
        self == ContentTarget::Pool(ExamPool::Hindi)
    }

    /// The exact number of passages a complete import holds (P04 "exact
    /// counts"). Number + Punctuation is Golu's Track 03 list of 50 drills
    /// (ALN-001 … ALN-050).
    #[must_use]
    pub fn expected_count(self) -> usize {
        match self {
            ContentTarget::Product(ProductId::NumberPunctuation) => 50,
            ContentTarget::Product(ProductId::TypingFlow) => 100,
            ContentTarget::Product(_) => 200,
            ContentTarget::Pool(_) => 500,
        }
    }

    /// The product, when this is one.
    #[must_use]
    pub fn product(self) -> Option<ProductId> {
        match self {
            ContentTarget::Product(p) => Some(p),
            ContentTarget::Pool(_) => None,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn targets_are_nine_products_and_two_pools_with_unique_slugs() {
        let all = ContentTarget::all();
        assert_eq!(all.len(), 11);
        let mut slugs: Vec<&str> = all.iter().map(|t| t.slug()).collect();
        slugs.sort_unstable();
        slugs.dedup();
        assert_eq!(slugs.len(), 11);
        for t in all {
            assert_eq!(ContentTarget::from_slug(t.slug()).unwrap(), t);
        }
        assert!(ContentTarget::from_slug("nope").is_err());
    }

    #[test]
    fn expected_counts_add_up_to_2600() {
        let total: usize = ContentTarget::all()
            .into_iter()
            .map(ContentTarget::expected_count)
            .sum();
        // PRD 17.1 planned 2600 with 100 Number + Punctuation drills; Golu's
        // Track 03 list (P09 content) has 50, so the real total is 2550.
        assert_eq!(total, 2600 - 50, "PRD 17.1: 2600 exercises, Track 03 is 50");
        assert_eq!(
            ContentTarget::Product(ProductId::NumberPunctuation).expected_count(),
            50
        );
    }

    #[test]
    fn statuses_round_trip() {
        for s in [
            ContentStatus::Verified,
            ContentStatus::Provisional,
            ContentStatus::GeneratedReviewPending,
        ] {
            assert_eq!(ContentStatus::parse(s.as_str()).unwrap(), s);
        }
        assert!(ContentStatus::parse("official").is_err());
        assert_eq!(ContentStatus::default(), ContentStatus::Provisional);
    }

    #[test]
    fn the_hindi_pool_is_typed_on_both_remington_layouts() {
        let hindi = ContentTarget::Pool(ExamPool::Hindi);
        assert_eq!(
            hindi.typing_layouts(),
            [LayoutId::RemingtonGail, LayoutId::RemingtonCbi]
        );
        assert!(hindi.has_legacy_form());
        assert!(!ContentTarget::Pool(ExamPool::English).has_legacy_form());
    }
}
